"""
Module defining some basic functionality for streamlining the process of benchmarking
the different influence calculation techniques. In particular, the main evaluation
task will be the detection of mislabeled examples (synthetically generated by adding
noise to labels in the training set) by looking at the most self-influential examples.
"""
from abc import abstractmethod
import os
import random
import json
from warnings import warn

import numpy as np

from .influence_factory import InfluenceCalculatorFactory
from .._optional_imports import import_optional_attr, import_optional_module
from ..common import BaseBackend, Framework, get_available_frameworks, get_backend, get_backend_for_tensor
from ..types import Tuple, Dict, Any, Optional, List


class BaseTrainingProcedure:
    """
    A basic interface for neural network's learning procedure for streamlining batch
    training groups of models and facilitate the statistical test of the influence
    calculation's methods performances.
    """

    @abstractmethod
    def train(
            self,
            training_dataset: Any,
            test_dataset: Any,
            train_batch_size: int = 128,
            test_batch_size: int = 128,
            log_path: Optional[str] = None
    ) -> Tuple[float, float, Any, Any]:
        """
        Trains the model on the training dataset using a given size for the batches, and
        performs validation on the test dataset, eventually saving the model in the provided
        path (if not None).

        Parameters
        ----------
        training_dataset
            A TF dataset with all the data on which the model must be trained.
        test_dataset
            A TF dataset with all the data on which to validate the model's performance.
        train_batch_size
            An integer with the size of the batches on which to train the model.
        test_batch_size
            An integer with the size of the batches on which to perform the validation.
        log_path
            An (optional) string specifying where to save the model (if desired).

        Returns
        -------
        A tuple with: (the train accuracy, the test accuracy, the final model, the information from the model saver)
        """
        raise NotImplementedError


class MislabelingDetectorEvaluator:
    """
    A class implementing a benchmarking pipeline for influence calculators based on their capacity
    to point out the most self-influential examples as being the (voluntarily added) mislabeled
    examples in the training dataset.

    Notes
    -----
    As such, the experiments will consist on training a model using the specified procedure on a
    noisy dataset, computing the self-influence of each of the training dataset's points, sorting
    them by it and seeing how fast we can find all the mislabeled examples. In an industrial setting,
    the derivative of this curve close to zero will be paramount, as this means that we can find a
    considerable percentage of these samples by looking at a low percentage of the dataset (and thus,
    be done by a human operator).

    Parameters
    ----------
    training_dataset
            A TF dataset with all the data on which the model must be trained.
    test_dataset
        A TF dataset with all the data on which to validate the model's performance.
    training_procedure
        An object implementing the BaseTrainingProcedure interface and describing how the model
        must be trained.
    nb_classes
        An integer with the amount of classes of the classification problem.
    mislabeling_ratio
        A float with the ratio of noise to add to the training dataset's labels (ranging from 0. to 1.).
    train_batch_size
        An integer with the size of the batches on which to train the model.
    test_batch_size
        An integer with the size of the batches on which to perform the validation.
    config
        A dictionary with the configuration to save it alongside the results for traceability.
    """

    def __init__(
            self,
            training_dataset: Any,
            test_dataset: Any,
            training_procedure: BaseTrainingProcedure,
            nb_classes: int,
            mislabeling_ratio: float,
            train_batch_size: int = 128,
            test_batch_size: int = 128,
            influence_batch_size: Optional[int] = None,
            config: Optional[Dict] = None,
            backend: Optional[Any] = None) -> None:
        assert 0. < mislabeling_ratio < 1.
        self.training_dataset = training_dataset
        self.train_batch_size = train_batch_size
        self.test_dataset = test_dataset
        self.test_batch_size = test_batch_size
        self.training_procedure = training_procedure
        self.nb_classes = nb_classes
        self.mislabeling_ratio = mislabeling_ratio
        if influence_batch_size is None:
            self.influence_batch_size = self.train_batch_size
        else:
            self.influence_batch_size = influence_batch_size

        if config is None:
            self.config = {}
        else:
            self.config = config

        self.backend = self._resolve_backend(backend, training_dataset)

    @staticmethod
    def _resolve_backend(backend: Optional[Any], dataset: Any) -> BaseBackend:
        """Resolve backend either from explicit value or from dataset content."""
        if backend is not None:
            if isinstance(backend, BaseBackend):
                return backend
            if isinstance(backend, Framework):
                return get_backend(backend)
            raise ValueError(f"Unsupported backend argument type: {type(backend)}")

        def _extract_first_tensor(obj: Any) -> Any:
            """Extract first tensor-like leaf from nested dataset elements."""
            if isinstance(obj, (list, tuple)):
                for item in obj:
                    tensor = _extract_first_tensor(item)
                    if tensor is not None:
                        return tensor
                return None
            return obj

        try:
            first_item = next(iter(dataset))
            first_tensor = _extract_first_tensor(first_item)
            if first_tensor is not None:
                return get_backend_for_tensor(first_tensor)
        except (StopIteration, TypeError, ValueError):
            pass

        available_frameworks = get_available_frameworks()
        if len(available_frameworks) == 1:
            return get_backend(available_frameworks[0])

        raise ValueError(
            "Could not infer backend from dataset. Please pass `backend` explicitly "
            "using Framework.TENSORFLOW / Framework.PYTORCH or a backend instance."
        )

    def bench(
            self,
            influence_calculator_factories: Dict[str, InfluenceCalculatorFactory],
            nbr_of_evaluation: int,
            path_to_save: str,
            seed: int = 0,
            verbose: bool = True,
            use_tensorboard: bool = False
    ) -> Dict[str, Tuple[np.ndarray, np.ndarray, float]]:
        """
        Performs the whole benchmark for a group of influence calculator techniques and a number of
        evaluations for each of them (for statistical significance).

        Parameters
        ----------
        influence_calculator_factories
            A dictionary with the name of the influence calculator technique and a factory for creating
            instances for them.
        nbr_of_evaluation
            An integer with the amount of evaluations per method.
        path_to_save
            A string specifying the path to save the results.
        seed
            An integer for setting the seed on all the random number generators.
        verbose
            A boolean indicating whether progress is reported in stdout or not.
        use_tensorboard
            A boolean indicating if the results are to be progressively logged into tensorboard.

        Returns
        -------
        result
            A dictionary with the name of each method and its results.
        """
        result = {}
        for name, influence_calculator_factory in influence_calculator_factories.items():
            if verbose:
                print("starting to evaluate=" + str(name))

            curves, mean_curve, roc = self.evaluate(influence_calculator_factory, nbr_of_evaluation, seed, verbose,
                                                    path_to_save, use_tensorboard, name)

            result[name] = (curves, mean_curve, roc)

            if verbose:
                print(name + " | mean roc=" + str(roc))

        return result

    def evaluate(
            self,
            influence_factory: InfluenceCalculatorFactory,
            nbr_of_evaluation: int,
            seed: int = 0,
            verbose: bool = True,
            path_to_save: Optional[str] = None,
            use_tensorboard: bool = False,
            method_name: Optional[str] = None
    ) -> Tuple[np.ndarray, np.ndarray, float]:
        """
        Performs one benchmark evaluation over one influence calculator technique the specified number
        of times (for statistical significance).

        Parameters
        ----------
        influence_factory
            A factory for instantiating objects for a given influence calculator technique.
        nbr_of_evaluation
            An integer with the amount of evaluations per method.
        seed
            An integer for setting the seed on all the random number generators.
        verbose
            A boolean indicating whether progress is reported in stdout or not.
        path_to_save
            A string specifying the path to save the results.
        use_tensorboard
            A boolean indicating if the results are to be progressively logged into tensorboard.
        method_name
            An optional string with the experience's name.

        Returns
        -------
        curves, mean_curve, roc
            A tuple with the experience's results: (each of the individual curves, the mean curve, the ROC)
        """
        curve_list: List[np.ndarray] = []

        method = method_name if method_name is not None else 'experiment'
        use_tensorboard, path_to_save = self._resolve_logging_options(use_tensorboard, path_to_save)
        self._prepare_result_directory(path_to_save, method)

        for index in range(nbr_of_evaluation):
            file_writer = self._create_seed_writer(path_to_save, method, index) if use_tensorboard else None
            sorted_curve = self._evaluate_single_seed(influence_factory, seed, index, path_to_save, method, verbose)
            curve_list.append(sorted_curve)

            if use_tensorboard:
                assert file_writer is not None
                self._log_seed_metrics(file_writer, sorted_curve, index)

            if path_to_save is not None:
                self._save_intermediate_results(path_to_save, method, curve_list)

        curves_array, mean_curve, roc = self.__build(curve_list)

        if use_tensorboard:
            assert path_to_save is not None
            self._log_summary_metrics(path_to_save, method, roc, mean_curve)

        return curves_array, mean_curve, roc

    def _resolve_logging_options(
        self,
        use_tensorboard: bool,
        path_to_save: Optional[str],
    ) -> Tuple[bool, Optional[str]]:
        """Validate logging options and infer default output directory if needed."""
        if use_tensorboard and self.backend.framework != Framework.TENSORFLOW:
            warn("TensorBoard logging is currently only supported with the TensorFlow backend. Disabling it.")
            return False, path_to_save

        if use_tensorboard and path_to_save is None:
            return True, "./"

        return use_tensorboard, path_to_save

    def _prepare_result_directory(self, path_to_save: Optional[str], method: str) -> None:
        """Create output directory and save benchmark configuration."""
        if path_to_save is None:
            return

        dirname = os.path.join(path_to_save, method)
        if not os.path.exists(dirname):
            os.makedirs(dirname)

        with open(os.path.join(dirname, "config.json"), 'w', encoding="utf-8") as fp:
            json.dump(self.config, fp, indent=4)

    @staticmethod
    def _create_seed_writer(path_to_save: Optional[str], method: str, index: int) -> Any:
        """Create a TensorBoard writer for one seed evaluation."""
        assert path_to_save is not None
        experiment_name = method + "_" + str(index)
        tf = import_optional_module("tensorflow", extra="tensorflow")
        return tf.summary.create_file_writer(
            os.path.join(path_to_save, method, "seed" + str(index)),
            filename_suffix=experiment_name,
        )

    def _evaluate_single_seed(
        self,
        influence_factory: InfluenceCalculatorFactory,
        seed: int,
        index: int,
        path_to_save: Optional[str],
        method: str,
        verbose: bool,
    ) -> np.ndarray:
        """Run one benchmark seed and return its detection curve."""
        if self.backend.framework == Framework.TENSORFLOW:
            tf = import_optional_module("tensorflow", extra="tensorflow")
            tf.keras.backend.clear_session()

        self.set_seed(seed + index, self.backend)
        noisy_training_dataset, noisy_label_indexes = self.build_noisy_training_dataset()
        noisy_label_index_array = noisy_label_indexes[0]

        log_path = None if path_to_save is None else os.path.join(path_to_save, method, "seed" + str(index))
        acc_train, acc_test, model, data_train = self.training_procedure.train(
            noisy_training_dataset,
            self.test_dataset,
            self.train_batch_size,
            self.test_batch_size,
            log_path=log_path,
        )

        shuffled_dataset = self.backend.shuffle_dataset(noisy_training_dataset, 1000)
        influence_dataset = self.backend.batch_dataset(shuffled_dataset, self.influence_batch_size)
        influence_calculator = influence_factory.build(influence_dataset, model, data_train)
        scoring_dataset = self.backend.batch_dataset(noisy_training_dataset, self.influence_batch_size)
        influences_values = influence_calculator._compute_influence_values(scoring_dataset)  # pylint: disable=W0212

        sorted_influences_indexes = np.argsort(-np.squeeze(self.backend.to_numpy(influences_values)))
        sorted_curve = self.__compute_curve(sorted_influences_indexes, noisy_label_index_array)
        roc = self._compute_roc(sorted_curve)

        if verbose:
            print(
                "seed nbr=" + str(index)
                + " | acc train=" + str(acc_train)
                + " | acc test=" + str(acc_test)
                + " | roc=" + str(roc)
            )

        return sorted_curve

    def _log_seed_metrics(self, file_writer: Any, sorted_curve: np.ndarray, index: int) -> None:
        """Log one seed ROC metrics to TensorBoard."""
        roc = self._compute_roc(sorted_curve)
        tf = import_optional_module("tensorflow", extra="tensorflow")
        with file_writer.as_default():
            tf.summary.scalar("roc_value", roc, index)
            self.plot_tensorboard_roc(sorted_curve, "roc_curve")

    def _save_intermediate_results(self, path_to_save: str, method: str, curves: List[np.ndarray]) -> None:
        """Persist intermediate benchmark curves during evaluation."""
        curves_, mean_curve_, roc_ = self.__build(curves)
        self.__save(os.path.join(path_to_save, method, "data.npy"), curves_, mean_curve_, roc_)

    def _log_summary_metrics(self, path_to_save: str, method: str, roc: float, mean_curve: np.ndarray) -> None:
        """Log final aggregated ROC metrics to TensorBoard."""
        tf = import_optional_module("tensorflow", extra="tensorflow")
        file_writer = tf.summary.create_file_writer(os.path.join(path_to_save, "synthesis", method))
        with file_writer.as_default():
            tf.summary.scalar("roc_mean", roc, 0)
            tf.summary.scalar("roc_mean", roc, 1)
            self.plot_tensorboard_roc(mean_curve, "roc_curve_mean")

    @staticmethod
    def plot_tensorboard_roc(curve: np.ndarray, experiment_name: str):
        """
        Plots a mislabeled samples detection ROC curve on tensorboard.

        Parameters
        ----------
        curve
            A numpy array with the experiment's curve
        experiment_name
            A string with the experiment's name
        """
        tf = import_optional_module("tensorflow", extra="tensorflow")
        for i, c in enumerate(curve):
            tf.summary.scalar(experiment_name, c, i)

    def __build(self, curves: List[np.ndarray]) -> Tuple[np.ndarray, np.ndarray, float]:
        """
        Formats the curves, computes the mean curve and the ROC.

        Parameters
        ----------
        curves
            A list with the experiment's curves mislabeled sample detection curves.
        Returns
        -------
        curves, mean_curve, roc
            A tuple with: (curves in numpy array format, the mean curve, the roc value)
        """
        curves_array = np.asarray(curves)
        mean_curve = np.mean(curves_array, axis=0)
        roc = self._compute_roc(mean_curve)

        return curves_array, mean_curve, roc

    @staticmethod
    def _compute_roc(curve: np.ndarray) -> float:
        """
        Computes the ROC value of the curve.

        Parameters
        ----------
        curve
            A numpy array with a curve.

        Returns
        -------
        roc
            The roc value.
        """
        roc = np.mean(curve)
        return roc

    @staticmethod
    def set_seed(seed: int, backend: Optional[BaseBackend] = None):
        """
        Sets all the random seeds on TensorFlow, numpy and python for traceability.

        Parameters
        ----------
        seed
            An integer with the seed value.
        """
        np.random.seed(seed)
        random.seed(seed)

        if backend is None or backend.framework == Framework.TENSORFLOW:
            try:
                tf = import_optional_module("tensorflow", extra="tensorflow")
                tf.random.set_seed(seed)
            except ImportError:
                pass

        if backend is None or backend.framework == Framework.PYTORCH:
            try:
                torch = import_optional_module("torch", extra="pytorch")
                torch.manual_seed(seed)
                if torch.cuda.is_available():
                    torch.cuda.manual_seed_all(seed)
            except ImportError:
                pass

    @staticmethod
    def __compute_curve(sorted_influences_indexes: np.ndarray, noisy_label_indexes: np.ndarray) -> np.ndarray:
        """
        Computes the mislabeled sample detection curve using the indices of the samples sorted
        by their self-influence and the ground-truth indices of the target points.

        Parameters
        ----------
        sorted_influences_indexes
            A numpy array with the sample's indices sorted by their self-influence.
        noisy_label_indexes
            A numpy array with the dataset's mislabeled examples' ground-truth.

        Returns
        -------
        curve
            A numpy array with the detection curve as we progressively scan the dataset.
        """
        index = np.isin(np.ravel(sorted_influences_indexes), noisy_label_indexes)
        index = index.astype(np.int32)
        curve = np.cumsum(index)
        if curve[-1] != 0:
            curve = curve / curve[-1]

        return curve

    def build_noisy_training_dataset(self) -> Tuple[Any, Tuple[np.ndarray, ...]]:
        """
        Generates a noisy version of the object's own dataset. In particular, it will include noise
        in the label information (i.e. the label will be switched at random). More noise will
        effectively impact the model's capacity to predict correctly on the test set, as it will
        need to learn to use spurious correlations to attain the 100% accuracy on the training
        dataset.

        Returns
        -------
        noisy_dataset, noise_indexes
            A tuple with the noisy dataset and a numpy array with the flipped labels (used for validation
            during the evaluation).
        """
        if self.backend.framework == Framework.TENSORFLOW:
            return self._build_noisy_training_dataset_tensorflow()

        return self._build_noisy_training_dataset_iterable()

    def _build_noisy_training_dataset_tensorflow(self) -> Tuple[Any, Tuple[np.ndarray, ...]]:
        """Build a noisy training dataset for the TensorFlow backend."""
        tf = import_optional_module("tensorflow", extra="tensorflow")

        dataset_size = int(tf.data.experimental.cardinality(self.training_dataset).numpy())
        noise_mask = self._build_noise_mask(dataset_size)
        noise_mask_dataset = tf.data.Dataset.from_tensor_slices(noise_mask)
        noisy_dataset = tf.data.Dataset.zip((self.training_dataset, noise_mask_dataset))
        noisy_dataset = noisy_dataset.map(self._noise_map_tensorflow)

        return noisy_dataset, self._noise_indexes(noise_mask)

    @staticmethod
    def _noise_map_tensorflow(z: Any, y_mask: Any) -> Tuple[Any, Any]:
        """Flips one TensorFlow sample label according to a boolean mask."""
        tf = import_optional_module("tensorflow", extra="tensorflow")
        x, y = z
        y_noise = tf.random.uniform(shape=(1,)) * tf.cast((tf.shape(y)[-1] - 1), dtype=tf.float32)
        y_noise = tf.cond(
            y_noise > tf.cast(tf.argmax(y), dtype=tf.float32),
            lambda: y_noise + 1,
            lambda: y_noise,
        )
        y_noise = tf.cast(y_noise, dtype=tf.int32)
        y_noise = tf.cast(tf.squeeze(tf.one_hot(y_noise, tf.shape(y)[-1]), axis=0), dtype=y.dtype)
        y = tf.where(y_mask, y, y_noise)
        return x, y

    def _build_noisy_training_dataset_iterable(self) -> Tuple[Any, Tuple[np.ndarray, ...]]:
        """Build a noisy training dataset for iterable / PyTorch inputs."""
        torch, data_loader_cls = self._load_pytorch_dependencies()
        samples = self._extract_training_samples(data_loader_cls)
        noise_mask = self._build_noise_mask(len(samples))

        noisy_samples = []
        for idx, (x, y) in enumerate(samples):
            if noise_mask[idx]:
                noisy_samples.append((x, y))
            else:
                noisy_samples.append((x, self._flip_label(y, torch)))

        return noisy_samples, self._noise_indexes(noise_mask)

    @staticmethod
    def _load_pytorch_dependencies() -> Tuple[Any, Any]:
        """Import and return PyTorch runtime dependencies used by benchmark datasets."""
        try:
            torch = import_optional_module("torch", extra="pytorch")
            data_loader_cls = import_optional_attr("torch.utils.data", "DataLoader", extra="pytorch")
        except ImportError as exc:
            raise ImportError("PyTorch backend requested but PyTorch is not installed.") from exc
        return torch, data_loader_cls

    def _extract_training_samples(self, data_loader_cls: Any) -> List[Tuple[Any, Any]]:
        """Extract samples from DataLoader or generic iterable datasets."""
        if isinstance(self.training_dataset, data_loader_cls):
            return self._extract_samples_from_dataloader()
        return self._extract_samples_from_iterable()

    def _extract_samples_from_dataloader(self) -> List[Tuple[Any, Any]]:
        """Flatten DataLoader batches into a list of individual (x, y) samples."""
        samples = []
        for batch in self.training_dataset:
            x_batch, y_batch = batch[0], batch[1]
            batch_size = x_batch.shape[0]
            for idx in range(batch_size):
                samples.append((x_batch[idx], y_batch[idx]))
        return samples

    def _extract_samples_from_iterable(self) -> List[Tuple[Any, Any]]:
        """Extract samples from a generic iterable dataset."""
        samples = []
        for item in self.training_dataset:
            if isinstance(item, (list, tuple)) and len(item) >= 2:
                samples.append((item[0], item[1]))
            else:
                raise ValueError("Training dataset items should be tuples of (x, y).")
        return samples

    def _flip_label(self, label: Any, torch: Any) -> Any:
        """Flip one label to a random class different from its original class."""
        if isinstance(label, torch.Tensor):
            return self._flip_torch_label(label, torch)
        return self._flip_array_label(label)

    def _flip_torch_label(self, label: Any, torch: Any) -> Any:
        """Flip a PyTorch label tensor while preserving representation format."""
        if label.ndim == 0 or (label.ndim == 1 and label.numel() == 1):
            y_class = int(label.item())
            y_noise = self._sample_different_class(y_class, self.nb_classes)
            return torch.tensor(y_noise, dtype=label.dtype, device=label.device)

        num_classes = int(label.shape[-1])
        y_class = int(torch.argmax(label).item())
        y_noise = self._sample_different_class(y_class, num_classes)
        y_flipped = torch.zeros_like(label)
        y_flipped[y_noise] = 1
        return y_flipped

    def _flip_array_label(self, label: Any) -> np.ndarray:
        """Flip a non-torch one-hot encoded label."""
        y_array = np.asarray(label)
        y_class = int(np.argmax(y_array))
        num_classes = int(y_array.shape[-1])
        y_noise = self._sample_different_class(y_class, num_classes)
        y_flipped = np.zeros_like(y_array)
        y_flipped[y_noise] = 1
        return y_flipped

    @staticmethod
    def _sample_different_class(y_class: int, num_classes: int) -> int:
        """Sample a class index in [0, num_classes) that differs from y_class."""
        y_noise = np.random.randint(0, num_classes - 1)
        if y_noise >= y_class:
            y_noise += 1
        return y_noise

    def _build_noise_mask(self, dataset_size: int) -> np.ndarray:
        """Sample a boolean mask indicating which labels should remain unchanged."""
        return np.random.uniform(size=(dataset_size,)) > self.mislabeling_ratio

    @staticmethod
    def _noise_indexes(noise_mask: np.ndarray) -> Tuple[np.ndarray, ...]:
        """Return indices of the samples whose labels were flipped."""
        return np.where(np.logical_not(noise_mask))

    @staticmethod
    def __save(path_to_save: str, curves: np.ndarray, mean_curve: np.ndarray, roc: float) -> None:
        """
        Saves an evaluation's results to the disk.

        Parameters
        ----------
        path_to_save
            A string with the path into which to save the results.
        curves
            A numpy array with the different detection curves.
        mean_curve
            A numpy array with the mean detection curve.
        roc
            A float with the ROC value.
        """
        dirname = os.path.dirname(path_to_save)
        if not os.path.exists(dirname):
            os.makedirs(dirname)
        np.save(path_to_save, np.array((curves, mean_curve, roc), dtype=object), allow_pickle=True)
